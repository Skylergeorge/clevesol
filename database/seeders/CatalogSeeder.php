    public function run(): void
    {
        foreach ($this->catalog() as $index => $cat) {
            $attributes = [
                'name' => $cat['name'],
                'tagline' => $cat['tagline'],
                'description' => $cat['description'],
                'icon' => $cat['icon'],
                'accent' => $cat['accent'],
                'sort_order' => $index,
                'is_published' => true,
            ];

            $category = ! empty($cat['refresh'])
                ? Category::query()->updateOrCreate(['slug' => Str::slug($cat['name'])], $attributes)
                : Category::query()->firstOrCreate(['slug' => Str::slug($cat['name'])], $attributes);

            foreach ($cat['products'] as $pIndex => $p) {
                $slug = Str::slug($cat['name'].'-'.$p['name']);
                $imageFile = public_path("images/products/{$slug}.jpg");
                $imagePath = file_exists($imageFile) ? "/images/products/{$slug}.jpg" : null;

                $payload = [
                    'category_id' => $category->id,
                    'image_path' => $imagePath,
                    'name' => $p['name'],
                    'subtitle' => $p['subtitle'] ?? null,
                    'sku' => $p['sku'] ?? 'CLV-'.strtoupper(Str::random(6)),
                    'brand' => $p['brand'] ?? 'Clevesol',
                    'description' => $p['description'] ?? $this->fallbackDescription($p['name'], $cat['name']),
                    'features' => $p['features'] ?? $this->fallbackFeatures(),
                    'certifications' => $p['certifications'] ?? ['CE', 'ANSI', 'EN', 'ISO'],
                    'sizes' => $p['sizes'] ?? null,
                    'badge' => $p['badge'] ?? null,
                    'price' => $p['price'],
                    'compare_price' => $p['compare_price'] ?? null,
                    'rating' => $p['rating'] ?? round(mt_rand(455, 499) / 100, 2),
                    'reviews_count' => $p['reviews'] ?? mt_rand(12, 340),
                    'stock' => $p['stock'] ?? mt_rand(40, 500),
                    'is_featured' => $p['featured'] ?? false,
                    'is_published' => true,
                    'sort_order' => $pIndex,
                ];

                $product = ! empty($cat['refresh'])
                    ? Product::query()->updateOrCreate(['slug' => $slug], $payload)
                    : Product::query()->firstOrCreate(['slug' => $slug], $payload);

                if ($imagePath && $product->image_path !== $imagePath) {
                    $product->update(['image_path' => $imagePath]);
                }
            }
        }
    }

